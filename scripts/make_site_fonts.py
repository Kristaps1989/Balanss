"""Subset Manrope for the website and write backend/src/site/fonts.ts.

The site serves its own fonts (no font CDN, so visitors' IP addresses go nowhere else).
Each weight is cut down to Latin + Latvian and stored as base64 WOFF2, so the server
bundle needs no asset copying.

    pip install fonttools brotli
    python scripts/make_site_fonts.py
"""
import base64
import io
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "node_modules" / "@expo-google-fonts" / "manrope"
OUT = ROOT / "backend" / "src" / "site" / "fonts.ts"

WEIGHTS = {300: "300Light", 400: "400Regular", 600: "600SemiBold", 700: "700Bold"}
UNICODES = "U+0020-007E,U+00A0-00FF,U+0100-017F,U+2013,U+2014,U+2018-201E,U+2022,U+2026,U+2192,U+2212"


def woff2(path: Path) -> bytes:
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = ["kern", "liga", "tnum", "lnum", "case"]
    options.unicodes = subset.parse_unicodes(UNICODES)
    font = TTFont(path)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=options.unicodes)
    subsetter.subset(font)
    font.flavor = "woff2"
    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue()


def main() -> None:
    lines = [
        "/** Generated by scripts/make_site_fonts.py (Manrope, Latin + Latvian subset, WOFF2). Do not edit. */",
        "export const SITE_FONTS: Record<number, string> = {",
    ]
    for weight, name in WEIGHTS.items():
        files = list(SRC.rglob(f"Manrope_{name}.ttf"))
        if not files:
            raise SystemExit(f"Manrope_{name}.ttf not found under {SRC}")
        data = woff2(files[0])
        print(f"manrope {weight}: {len(data) / 1024:.1f} KB")
        lines.append(f"  {weight}: '{base64.b64encode(data).decode()}',")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
